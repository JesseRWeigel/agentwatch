#!/usr/bin/env python3
"""Generate docs/index.html from the package, so the page cannot drift from the code.

    build_docs.py           rebuild the page
    build_docs.py --check   rebuild in memory and fail if the published page has drifted

Every board, every confidence and every reason on the page is produced by running the code against
the committed fixture. `verify.sh` rebuilds it and fails if the result differs from what is
committed.

Nothing from the machine that builds it appears on the page. The fixture's home is invented, and
the privacy scan checks this file's output with NO home path permitted at all, not even that one,
because a page is the thing most likely to be read by somebody who is not you.
"""

from __future__ import annotations

import html
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from scripts.measure import measure                              # noqa: E402

DOCS = os.path.join(ROOT, "docs")
PAGE = os.path.join(DOCS, "index.html")
DATA = os.path.join(DOCS, "measured.json")

STYLE = """
:root{color-scheme:light dark;--bg:#fbfaf8;--fg:#17181a;--muted:#5c616a;--line:#e4e5e8;
  --card:#fff;--warn:#a5342a;--ok:#1f6f43}
@media (prefers-color-scheme:dark){:root{--bg:#131416;--fg:#e9e7e3;--muted:#8f949c;
  --line:#25282c;--card:#191b1e;--warn:#e08a8a;--ok:#6fcf97}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);
  font:16px/1.6 ui-sans-serif,system-ui,-apple-system,Segoe UI,Roboto,sans-serif}
main{max-width:58rem;margin:0 auto;padding:3rem 1.25rem 4rem}
h1{font-size:clamp(1.9rem,5vw,2.6rem);margin:0 0 .3rem;letter-spacing:-.03em}
h2{font-size:1.15rem;margin:2.8rem 0 .6rem;padding-bottom:.35rem;border-bottom:1px solid var(--line)}
h3{font-size:.95rem;margin:1.6rem 0 .5rem;font-weight:600}
p{color:var(--muted);max-width:46rem}.lede{color:var(--fg);font-size:1.05rem}
pre{background:var(--card);border:1px solid var(--line);border-radius:8px;padding:.9rem 1rem;
  overflow-x:auto;font:12.5px/1.5 ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}
.wrap{overflow-x:auto}
table{width:100%;border-collapse:collapse;font-size:.85rem;min-width:32rem}
th,td{text-align:left;padding:.35rem .55rem;border-bottom:1px solid var(--line)}
th{color:var(--muted);font-weight:600}
code{background:var(--card);border:1px solid var(--line);border-radius:3px;padding:.08rem .3rem;
  font-size:.85em}
.warn{color:var(--warn);font-weight:600}.ok{color:var(--ok);font-weight:600}
.note{border-left:3px solid var(--line);padding-left:.9rem;margin:1rem 0;color:var(--muted)}
footer{margin-top:3.5rem;color:var(--muted);font-size:.85rem}
a{color:inherit}
"""


def render() -> tuple[str, dict]:
    payload = measure()
    board_text = payload["rendered_board"]
    totals = payload["totals"]

    rows = []
    for session in payload["sessions"]:
        certain = session["certain"]
        badge = ('<span class="ok">certain</span>' if certain
                 else '<span class="warn">a guess</span>')
        rows.append(
            f"<tr><td><code>{session['pid']}</code></td>"
            f"<td>{html.escape(str(session['cwd_basename'] or 'not readable'))}</td>"
            f"<td>{html.escape(session['confidence'])}</td><td>{badge}</td>"
            f"<td>{html.escape(session['reason'])}</td></tr>")

    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>agentwatch</title>
<meta name="description" content="Every Claude Code and codex session on one machine, found in
the process table rather than reported by an orchestrator.">
<style>{STYLE}</style>
</head>
<body>
<main>
  <h1>agentwatch</h1>
  <p class="lede">Every agent session on the machine, found in the process table. Not the ones an
  orchestrator launched, and not the ones that registered themselves somewhere. All of them,
  including the one you started by typing <code>claude</code> in a terminal an hour ago and
  forgot.</p>

  <h2>The board</h2>
  <p>Generated by running the code against the committed fixture, so this is what the tool
  actually prints and not a mockup. The fixture is synthetic: every path, user name and session id
  in it was invented for the test.</p>
  <pre>{html.escape(board_text)}</pre>

  <h2>Why a session and its log are hard to join</h2>
  <p>A running process gives you a pid and a working directory. The interesting state is in a
  JSONL log under a directory named after that working directory with the slashes replaced. Two
  things go wrong.</p>
  <p><b>The naming rule is not one rule.</b> On the machine this was written on, of 61 project
  directories that record a working directory, 59 follow <code>"/" &rarr; "-"</code> and 2 also map
  <code>"." &rarr; "-"</code>. Both conventions sit on the same disk, because a directory is
  created by whichever version was running at the time and is never migrated. The rule is also
  lossy in every version: <code>/a/b</code> and <code>/a-b</code> produce the same name, so even a
  perfect implementation cannot be inverted. So the directory name is a hint, and the working
  directory recorded inside the log decides.</p>
  <p><b>Two agents in one repository is normal.</b> When several logs fit, this says so. It does
  not pick the most recently modified one and present it as a fact, because a reader cannot tell a
  confident answer from a coin flip, and the button next to the answer sends SIGTERM.</p>

  <h3>What the fixture resolves to</h3>
  <div class=wrap><table><thead><tr><th>pid<th>where<th>confidence<th><th>why</tr></thead>
  <tbody>{''.join(rows)}</tbody></table></div>
  <p>{totals['certain']} of {totals['sessions']} are certain, {totals['ambiguous']} are
  ambiguous, and {totals['opaque']} is a process whose details this user may not read. That last
  one still gets a row: "nothing is running" and "something is running that you are not allowed to
  look at" must not print the same board, and the second is exactly when somebody is hunting for
  missing CPU.</p>

  <h2>Correlating everything at once beats correlating each alone</h2>
  <p>A log belongs to one session. When one process names its session on its command line, it
  claims that log, and a rival sharing the directory is then left with exactly one candidate. That
  turns a coin flip into an answer without guessing. It came from a real pair of sessions in one
  directory where the second was being reported as a choice between two logs, one of which was
  already spoken for.</p>

  <h2>One inference, marked as one</h2>
  <p>Nothing in a session log says "waiting for you to approve a tool call". What it says is that
  a tool was requested and no result has been written. That is also what a tool call looks like
  for its first few seconds, so the only thing separating a running test suite from a permission
  prompt nobody is looking at is how long it has been true. The threshold is a guess, so the
  reading is shown with the evidence beside it:</p>
  <div class="note">{html.escape(payload['parsing']['evidence_for_stale'])}</div>

  <footer>
    <p><a href="https://github.com/JesseRWeigel/agentwatch">agentwatch</a>. This page is generated
    from the package by <code>scripts/build_docs.py</code>, and the build fails if it drifts from
    the code. The fixture is synthetic and generated by <code>scripts/make_fixtures.py</code>, so
    nothing here came off anybody's machine.</p>
  </footer>
</main>
</body>
</html>
"""
    return page, payload


def main(argv) -> int:
    page, payload = render()
    text = json.dumps(payload, indent=2, sort_keys=True) + "\n"

    if "--check" in argv:
        for path, fresh, label in ((PAGE, page, "docs/index.html"),
                                   (DATA, text, "docs/measured.json")):
            if not os.path.isfile(path):
                print(f"  FAIL {label} does not exist, so it was never published")
                return 1
            with open(path, encoding="utf-8") as handle:
                if handle.read() != fresh:
                    print(f"  FAIL {label} is stale: rebuilding it from the package changed it")
                    return 1
        print(f"  the published page matches the package ({len(page) // 1024} KB)")
        return 0

    os.makedirs(DOCS, exist_ok=True)
    with open(PAGE, "w", encoding="utf-8") as handle:
        handle.write(page)
    with open(DATA, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote docs/index.html ({len(page) // 1024} KB) and docs/measured.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
